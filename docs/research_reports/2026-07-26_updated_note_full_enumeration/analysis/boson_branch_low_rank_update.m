function [weight_ratio, new_matrix, new_green, diagnostics] = ...
    boson_branch_low_rank_update( ...
        old_matrix, left_factor, old_right_factor, embedding, ...
        local_ratio, local_ratio_derivative, scalar_change)
  % Exact branch-resolved update for a local Gaussian path.
  %
  % The path is
  %   M(t) = L [I + E (D(t)-I) E^T] R,  0 <= t <= 1,
  % with M(0)=L R and D(0)=I.  E embeds the local Nambu space.
  % local_ratio(t) returns D(t), and local_ratio_derivative(t) returns dD/dt.

  dimension = rows(old_matrix);
  local_dimension = columns(embedding);
  identity = eye(dimension);
  local_identity = eye(local_dimension);
  old_green = (identity - old_matrix) \ identity;

  factorization_residual = ...
      norm(old_matrix - left_factor * old_right_factor, "fro");
  initial_ratio_residual = ...
      norm(local_ratio(0) - local_identity, "fro");
  if factorization_residual > 1e-9 || initial_ratio_residual > 1e-10
    error("Invalid local-update factorization.");
  endif

  update_left = left_factor * embedding;
  update_right = embedding' * old_right_factor;
  reduced_green = update_right * old_green * update_left;

  log_derivative = @(t) reduced_log_derivative( ...
      t, local_ratio, local_ratio_derivative, reduced_green, ...
      local_identity);
  [integrated_log_derivative, integration_error] = quadgk( ...
      log_derivative, 0, 1, "AbsTol", 1e-11, "RelTol", 1e-11, ...
      "MaxIntervalCount", 4096);

  endpoint_difference = local_ratio(1) - local_identity;
  endpoint_reduced_matrix = ...
      local_identity - endpoint_difference * reduced_green;
  endpoint_determinant_ratio = det(endpoint_reduced_matrix);
  if abs(endpoint_determinant_ratio) < 1e-13
    error("The proposed path ends at a bosonic determinant pole.");
  endif

  % The real part is fixed from the endpoint magnitude.  The integrated
  % imaginary part retains every 2*pi winding and therefore the lift sign.
  continuous_log_determinant_ratio = ...
      log(abs(endpoint_determinant_ratio)) + ...
      1i * imag(integrated_log_derivative);
  weight_ratio = exp( ...
      scalar_change - 0.5 * continuous_log_determinant_ratio);

  new_matrix = old_matrix + ...
      update_left * endpoint_difference * update_right;
  woodbury_denominator = ...
      local_identity - reduced_green * endpoint_difference;
  new_green = old_green + ...
      old_green * update_left * endpoint_difference * ...
      (woodbury_denominator \ (update_right * old_green));

  direct_new_green = (identity - new_matrix) \ identity;
  green_update_residual = ...
      norm(new_green - direct_new_green, "fro") / ...
      max(1, norm(direct_new_green, "fro"));
  determinant_lemma_residual = abs( ...
      det(identity - new_matrix) / det(identity - old_matrix) - ...
      endpoint_determinant_ratio);

  sample_points = linspace(0, 1, 2001);
  minimum_reduced_determinant = Inf;
  minimum_reduced_singular_value = Inf;
  for point = 1:length(sample_points)
    local_difference = local_ratio(sample_points(point)) - local_identity;
    reduced_matrix = local_identity - local_difference * reduced_green;
    reduced_determinant = det(reduced_matrix);
    minimum_reduced_determinant = min( ...
        minimum_reduced_determinant, abs(reduced_determinant));
    minimum_reduced_singular_value = min( ...
        minimum_reduced_singular_value, min(svd(reduced_matrix)));
  endfor
  if minimum_reduced_determinant < 1e-10 || ...
     minimum_reduced_singular_value < 1e-10
    error("The proposed local path approaches a determinant pole.");
  endif

  diagnostics = struct( ...
      "continuous_log_determinant_ratio", ...
      continuous_log_determinant_ratio, ...
      "endpoint_determinant_ratio", endpoint_determinant_ratio, ...
      "integration_error", integration_error, ...
      "minimum_reduced_determinant", minimum_reduced_determinant, ...
      "minimum_reduced_singular_value", ...
      minimum_reduced_singular_value, ...
      "factorization_residual", factorization_residual, ...
      "green_update_residual", green_update_residual, ...
      "determinant_lemma_residual", determinant_lemma_residual);
endfunction


function answer = reduced_log_derivative( ...
    t, local_ratio, local_ratio_derivative, reduced_green, local_identity)
  % quadgk normally supplies a vector of quadrature points.  Evaluate the
  % small local matrix expression point by point and preserve that shape.
  answer = zeros(size(t));
  for point = 1:numel(t)
    local_difference = local_ratio(t(point)) - local_identity;
    derivative = local_ratio_derivative(t(point));
    reduced_matrix = local_identity - local_difference * reduced_green;
    answer(point) = ...
        -trace(reduced_matrix \ (derivative * reduced_green));
  endfor
endfunction
